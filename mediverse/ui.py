"""Shared UI helpers: session guard, page guard, filters, labels."""

from __future__ import annotations

from datetime import date

import streamlit as st

from mediverse.authz import AccessDenied, Perm, Principal

SYNTHETIC_NOTE = "All records are synthetic demonstration data. Nothing here is clinical advice."
AI_LABEL = ("AI-generated by Snowflake Cortex. Requires human review before any clinical or operational use. "
            "Not a diagnosis or treatment recommendation.")


def principal() -> Principal | None:
    return st.session_state.get("principal")


def guard(perm: Perm) -> Principal:
    """Call at the top of every page. Stops rendering if not signed in or not permitted."""
    p = principal()
    if p is None:
        st.warning("Please sign in.", icon=":material/lock:")
        st.stop()
    if not p.can(perm):
        from mediverse.services import repo
        repo().log_access(p, "PAGE", "OPEN", False, perm.value)
        st.error("You do not have permission to view this page.", icon=":material/block:")
        st.stop()
    return p


def show_denied(e: AccessDenied) -> None:
    st.error(str(e), icon=":material/block:")


def date_filter(key: str, default_start: date = date(2025, 1, 1), default_end: date = date(2025, 12, 31)):
    v = st.date_input("Date range", (default_start, default_end), min_value=date(2023, 1, 1),
                      max_value=date(2026, 12, 31), key=key)
    if isinstance(v, tuple) and len(v) == 2:
        return v
    return default_start, default_end


def department_filter(key: str) -> str | None:
    from mediverse.data import departments
    d = departments()
    opts = ["All departments"] + d["DEPARTMENT_NAME"].tolist()
    choice = st.selectbox("Department", opts, key=key)
    if choice == "All departments":
        return None
    return d.loc[d["DEPARTMENT_NAME"] == choice, "DEPARTMENT_ID"].iloc[0]


def money(v) -> str:
    v = float(v or 0)
    if abs(v) >= 1e6:
        return f"${v / 1e6:,.1f}M"
    if abs(v) >= 1e3:
        return f"${v / 1e3:,.1f}K"
    return f"${v:,.0f}"
