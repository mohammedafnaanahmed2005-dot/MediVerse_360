-- MediVerse 360: account objects. Run once.
-- Roles are created by SECURITYADMIN; objects are owned by MV_APP_OWNER (granted to SYSADMIN).

USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS MV_APP_OWNER  COMMENT = 'Owns MEDIVERSE360 objects and the Streamlit app';
CREATE ROLE IF NOT EXISTS MV_ADMIN      COMMENT = 'Direct-SQL: security/admin views';
CREATE ROLE IF NOT EXISTS MV_DOCTOR     COMMENT = 'Direct-SQL: clinical read';
CREATE ROLE IF NOT EXISTS MV_NURSE      COMMENT = 'Direct-SQL: nursing read';
CREATE ROLE IF NOT EXISTS MV_LAB        COMMENT = 'Direct-SQL: laboratory read';
CREATE ROLE IF NOT EXISTS MV_RADIOLOGY  COMMENT = 'Direct-SQL: imaging read';
CREATE ROLE IF NOT EXISTS MV_PHARMACIST COMMENT = 'Direct-SQL: pharmacy read';
CREATE ROLE IF NOT EXISTS MV_FINANCE    COMMENT = 'Direct-SQL: finance read';
CREATE ROLE IF NOT EXISTS MV_MANAGEMENT COMMENT = 'Direct-SQL: aggregated analytics';
GRANT ROLE MV_APP_OWNER TO ROLE SYSADMIN;
GRANT ROLE MV_ADMIN TO ROLE MV_APP_OWNER;
GRANT ROLE MV_DOCTOR TO ROLE MV_APP_OWNER;
GRANT ROLE MV_NURSE TO ROLE MV_APP_OWNER;
GRANT ROLE MV_LAB TO ROLE MV_APP_OWNER;
GRANT ROLE MV_RADIOLOGY TO ROLE MV_APP_OWNER;
GRANT ROLE MV_PHARMACIST TO ROLE MV_APP_OWNER;
GRANT ROLE MV_FINANCE TO ROLE MV_APP_OWNER;
GRANT ROLE MV_MANAGEMENT TO ROLE MV_APP_OWNER;

USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS MEDIVERSE_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE DATABASE IF NOT EXISTS MEDIVERSE360 COMMENT = 'MediVerse 360 - SYNTHETIC demo data only';
GRANT OWNERSHIP ON DATABASE MEDIVERSE360 TO ROLE MV_APP_OWNER COPY CURRENT GRANTS;
GRANT USAGE, OPERATE ON WAREHOUSE MEDIVERSE_WH TO ROLE MV_APP_OWNER;

USE ROLE ACCOUNTADMIN;
-- compute pool + Cortex access for the app owner
GRANT USAGE ON COMPUTE POOL SYSTEM_COMPUTE_POOL_CPU TO ROLE MV_APP_OWNER;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE MV_APP_OWNER;
-- Built-in PyPI mirror (no EAI needed; trial accounts cannot create EAIs).
GRANT DATABASE ROLE SNOWFLAKE.PYPI_REPOSITORY_USER TO ROLE MV_APP_OWNER;

USE ROLE MV_APP_OWNER;
USE WAREHOUSE MEDIVERSE_WH;
USE DATABASE MEDIVERSE360;
CREATE SCHEMA IF NOT EXISTS RAW;
CREATE SCHEMA IF NOT EXISTS STAGING;
CREATE SCHEMA IF NOT EXISTS CURATED;
CREATE SCHEMA IF NOT EXISTS SECURITY WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS APP;
CREATE STAGE IF NOT EXISTS RAW.CSV_STAGE DIRECTORY = (ENABLE = TRUE) ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE');
CREATE FILE FORMAT IF NOT EXISTS RAW.CSV_FMT TYPE = CSV PARSE_HEADER = TRUE
  FIELD_OPTIONALLY_ENCLOSED_BY = '"' EMPTY_FIELD_AS_NULL = TRUE;
