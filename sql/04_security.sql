-- SECURITY schema (managed access). Only MV_APP_OWNER reads these tables; the app
-- enforces per-user authorization on top. Timestamps are UTC TIMESTAMP_NTZ.
USE ROLE MV_APP_OWNER;
USE WAREHOUSE MEDIVERSE_WH;
USE SCHEMA MEDIVERSE360.SECURITY;

CREATE TABLE IF NOT EXISTS APP_ROLES (
  ROLE_CODE STRING PRIMARY KEY, DESCRIPTION STRING
);
MERGE INTO APP_ROLES t USING (
  SELECT column1 rc, column2 d FROM VALUES
  ('ADMIN','Users, roles, enrollment, configuration, audit'),
  ('DOCTOR','Permitted clinical, lab, imaging and treatment records'),
  ('NURSE','Assigned-department patient care and nursing records'),
  ('LAB_STAFF','Laboratory orders, specimens, results (biometric step-up)'),
  ('RADIOLOGY_STAFF','Imaging studies and radiology reports'),
  ('PHARMACIST','Prescriptions, inventory, dispensing, suppliers'),
  ('FINANCE_STAFF','Payroll, billing, budgets, expenditure'),
  ('MANAGEMENT','Aggregated operational and financial analytics')) s
ON t.ROLE_CODE = s.rc WHEN NOT MATCHED THEN INSERT VALUES (s.rc, s.d);

CREATE TABLE IF NOT EXISTS APP_USERS (
  USER_ID        STRING PRIMARY KEY,
  USERNAME       STRING NOT NULL UNIQUE,
  DISPLAY_NAME   STRING,
  ROLE_CODE      STRING NOT NULL REFERENCES APP_ROLES(ROLE_CODE),
  STAFF_ID       STRING,
  DEPARTMENT_ID  STRING,
  EMAIL          STRING,
  PASSWORD_HASH  STRING NOT NULL,
  STATUS         STRING DEFAULT 'ACTIVE',          -- ACTIVE | INACTIVE
  FLAGS          ARRAY  DEFAULT ARRAY_CONSTRUCT(),  -- PSYCH_ACCESS, MORTALITY_ACCESS
  FAILED_COUNT   NUMBER DEFAULT 0,
  LOCKED_UNTIL   TIMESTAMP_NTZ,
  CREATED_AT     TIMESTAMP_NTZ DEFAULT SYSDATE(),
  CREATED_BY     STRING,
  UPDATED_AT     TIMESTAMP_NTZ
);

-- Protected templates only: no raw images or raw keystrokes are stored.
CREATE TABLE IF NOT EXISTS BIOMETRIC_PROFILES (
  USER_ID          STRING PRIMARY KEY REFERENCES APP_USERS(USER_ID),
  STATUS           STRING,           -- ACTIVE | RESET
  ENROLL_SALT      STRING,
  FACE_TEMPLATE    VARIANT,
  TYPING_PROFILE   VARIANT,
  CONSENT_AT       TIMESTAMP_NTZ,
  ENROLLED_BY      STRING,
  VERIFIED_BY      STRING,
  IDENTITY_EVIDENCE STRING,          -- e.g. 'Staff ID card checked in person'
  ENROLLED_AT      TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS AUTH_CHALLENGES (
  CHALLENGE_HASH STRING PRIMARY KEY, USER_ID STRING, STAGE STRING,
  CREATED_AT TIMESTAMP_NTZ, EXPIRES_AT TIMESTAMP_NTZ, ATTEMPTS NUMBER,
  OTP_HASH STRING, OTP_EXPIRES_AT TIMESTAMP_NTZ, CONSUMED BOOLEAN
);

CREATE TABLE IF NOT EXISTS SESSIONS (
  SESSION_HASH STRING PRIMARY KEY, USER_ID STRING, ROLE_CODE STRING,
  CREATED_AT TIMESTAMP_NTZ, LAST_SEEN_AT TIMESTAMP_NTZ, EXPIRES_AT TIMESTAMP_NTZ,
  REVOKED BOOLEAN, AUTH_METHOD STRING
);

CREATE TABLE IF NOT EXISTS AUTH_EVENTS (
  EVENT_ID STRING, TS TIMESTAMP_NTZ, USERNAME STRING, USER_ID STRING,
  EVENT_TYPE STRING, OUTCOME STRING, REASON_CODES ARRAY,
  FACE_SCORE FLOAT, TYPING_SCORE FLOAT, AUTH_METHOD STRING, CHANNEL STRING
);

CREATE TABLE IF NOT EXISTS ACCESS_LOG (
  TS TIMESTAMP_NTZ DEFAULT SYSDATE(), USER_ID STRING, USERNAME STRING, ROLE_CODE STRING,
  RESOURCE STRING, ACTION STRING, RECORD_REF STRING, ALLOWED BOOLEAN, DETAIL STRING
);

CREATE TABLE IF NOT EXISTS ADMIN_AUDIT (
  TS TIMESTAMP_NTZ DEFAULT SYSDATE(), ADMIN_USER_ID STRING, ADMIN_USERNAME STRING,
  ACTION STRING, TARGET_USER_ID STRING, DETAILS VARIANT
);

CREATE TABLE IF NOT EXISTS CONFIG (KEY STRING PRIMARY KEY, VALUE VARIANT, UPDATED_AT TIMESTAMP_NTZ, UPDATED_BY STRING);

-- Biometric columns are masked for every role except the app owner.
CREATE MASKING POLICY IF NOT EXISTS BIOMETRIC_MASK AS (v VARIANT) RETURNS VARIANT ->
  CASE WHEN IS_ROLE_IN_SESSION('MV_APP_OWNER') THEN v ELSE NULL END;
ALTER TABLE BIOMETRIC_PROFILES MODIFY COLUMN FACE_TEMPLATE SET MASKING POLICY BIOMETRIC_MASK;
ALTER TABLE BIOMETRIC_PROFILES MODIFY COLUMN TYPING_PROFILE SET MASKING POLICY BIOMETRIC_MASK;

CREATE MASKING POLICY IF NOT EXISTS SECRET_STRING_MASK AS (v STRING) RETURNS STRING ->
  CASE WHEN IS_ROLE_IN_SESSION('MV_APP_OWNER') THEN v ELSE '***' END;
ALTER TABLE APP_USERS MODIFY COLUMN PASSWORD_HASH SET MASKING POLICY SECRET_STRING_MASK;

-- Read-only audit views for the MV_ADMIN direct-SQL role (no hashes, no templates).
CREATE OR REPLACE SECURE VIEW V_AUTH_EVENTS AS
  SELECT TS, USERNAME, USER_ID, EVENT_TYPE, OUTCOME, REASON_CODES, FACE_SCORE, TYPING_SCORE, AUTH_METHOD, CHANNEL FROM AUTH_EVENTS;
CREATE OR REPLACE SECURE VIEW V_USERS AS
  SELECT USER_ID, USERNAME, DISPLAY_NAME, ROLE_CODE, DEPARTMENT_ID, STATUS, FLAGS, LOCKED_UNTIL, CREATED_AT FROM APP_USERS;
GRANT USAGE ON DATABASE MEDIVERSE360 TO ROLE MV_ADMIN;
GRANT USAGE ON SCHEMA SECURITY TO ROLE MV_ADMIN;
GRANT SELECT ON VIEW V_AUTH_EVENTS TO ROLE MV_ADMIN;
GRANT SELECT ON VIEW V_USERS TO ROLE MV_ADMIN;
GRANT SELECT ON TABLE ADMIN_AUDIT TO ROLE MV_ADMIN;
GRANT SELECT ON TABLE ACCESS_LOG TO ROLE MV_ADMIN;

-- Server-side pepper, generated inside Snowflake (never typed or committed).
-- Trial accounts cannot create external access integrations, which Streamlit
-- needs in order to receive a Snowflake SECRET, so the pepper is kept in a
-- managed-access table masked for every role except MV_APP_OWNER.
-- LIMITATION: this is weaker than a SECRET/vault; on a paid account move it
-- to CREATE SECRET + EAI + ALTER STREAMLIT ... SET SECRETS.
CREATE TABLE IF NOT EXISTS APP_KEYS (KEY_NAME STRING PRIMARY KEY, KEY_VALUE STRING, CREATED_AT TIMESTAMP_NTZ DEFAULT SYSDATE());
ALTER TABLE APP_KEYS MODIFY COLUMN KEY_VALUE SET MASKING POLICY SECRET_STRING_MASK;
-- Never replaced once created (that would invalidate every password hash).
INSERT INTO APP_KEYS (KEY_NAME, KEY_VALUE)
  SELECT 'AUTH_PEPPER', SHA2(UUID_STRING() || UUID_STRING() || RANDOM()::STRING, 256)
  WHERE NOT EXISTS (SELECT 1 FROM APP_KEYS WHERE KEY_NAME = 'AUTH_PEPPER');

-- One-time token for creating the first administrator in the app's first-run screen.
-- Read it as MV_APP_OWNER:  SELECT KEY_VALUE FROM MEDIVERSE360.SECURITY.APP_KEYS WHERE KEY_NAME = 'BOOTSTRAP_TOKEN';
-- The app deletes it after use and only accepts it while no active ADMIN exists.
INSERT INTO APP_KEYS (KEY_NAME, KEY_VALUE)
  SELECT 'BOOTSTRAP_TOKEN', LEFT(SHA2(UUID_STRING() || RANDOM()::STRING, 256), 32)
  WHERE NOT EXISTS (SELECT 1 FROM APP_KEYS WHERE KEY_NAME = 'BOOTSTRAP_TOKEN')
    AND NOT EXISTS (SELECT 1 FROM APP_USERS WHERE ROLE_CODE = 'ADMIN' AND STATUS = 'ACTIVE');

CREATE TABLE IF NOT EXISTS MEDIVERSE360.APP.AI_OUTPUTS (
  OUTPUT_ID STRING DEFAULT UUID_STRING(), CREATED_AT TIMESTAMP_NTZ DEFAULT SYSDATE(),
  REQUESTED_BY STRING, TASK STRING, MODEL STRING, SOURCE_TABLE STRING, SOURCE_IDS ARRAY,
  OUTPUT VARIANT, REVIEW_STATUS STRING DEFAULT 'PENDING_REVIEW', REVIEWED_BY STRING, REVIEWED_AT TIMESTAMP_NTZ, REVIEW_NOTE STRING);
