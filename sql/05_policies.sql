-- Snowflake-side governance for DIRECT SQL access (Snowsight, BI tools) by MV_* roles.
-- The Streamlit app runs as MV_APP_OWNER and applies per-user rules in mediverse/authz.py;
-- these policies make sure the same restrictions hold outside the app.
USE ROLE MV_APP_OWNER;
USE WAREHOUSE MEDIVERSE_WH;
USE SCHEMA MEDIVERSE360.CURATED;

-- PII: visible to the owner, doctors and nurses only.
CREATE MASKING POLICY IF NOT EXISTS PII_STRING_MASK AS (v STRING) RETURNS STRING ->
  CASE WHEN IS_ROLE_IN_SESSION('MV_APP_OWNER') OR IS_ROLE_IN_SESSION('MV_DOCTOR') OR IS_ROLE_IN_SESSION('MV_NURSE')
       THEN v ELSE '***MASKED***' END;
CREATE MASKING POLICY IF NOT EXISTS PII_DATE_MASK AS (v DATE) RETURNS DATE ->
  CASE WHEN IS_ROLE_IN_SESSION('MV_APP_OWNER') OR IS_ROLE_IN_SESSION('MV_DOCTOR') OR IS_ROLE_IN_SESSION('MV_NURSE')
       THEN v ELSE DATE_FROM_PARTS(YEAR(v), 1, 1) END;
ALTER TABLE PATIENTS MODIFY COLUMN FIRST_NAME SET MASKING POLICY PII_STRING_MASK;
ALTER TABLE PATIENTS MODIFY COLUMN LAST_NAME SET MASKING POLICY PII_STRING_MASK;
ALTER TABLE PATIENTS MODIFY COLUMN PHONE SET MASKING POLICY PII_STRING_MASK;
ALTER TABLE PATIENTS MODIFY COLUMN EMAIL SET MASKING POLICY PII_STRING_MASK;
ALTER TABLE PATIENTS MODIFY COLUMN DATE_OF_BIRTH SET MASKING POLICY PII_DATE_MASK;

-- Salaries: owner and finance only.
CREATE MASKING POLICY IF NOT EXISTS SALARY_MASK AS (v NUMBER(14,2)) RETURNS NUMBER(14,2) ->
  CASE WHEN IS_ROLE_IN_SESSION('MV_APP_OWNER') OR IS_ROLE_IN_SESSION('MV_FINANCE') THEN v ELSE NULL END;
ALTER TABLE STAFF MODIFY COLUMN BASE_SALARY SET MASKING POLICY SALARY_MASK;
ALTER TABLE PAYROLL MODIFY COLUMN GROSS_PAY SET MASKING POLICY SALARY_MASK;
ALTER TABLE PAYROLL MODIFY COLUMN OVERTIME_PAY SET MASKING POLICY SALARY_MASK;
ALTER TABLE PAYROLL MODIFY COLUMN DEDUCTIONS SET MASKING POLICY SALARY_MASK;

-- Psychiatric / HIV diagnoses: rows hidden unless owner or doctor.
CREATE ROW ACCESS POLICY IF NOT EXISTS SENSITIVE_DX_RAP AS (is_sensitive BOOLEAN) RETURNS BOOLEAN ->
  NOT is_sensitive OR IS_ROLE_IN_SESSION('MV_APP_OWNER') OR IS_ROLE_IN_SESSION('MV_DOCTOR');
ALTER TABLE DIAGNOSES ADD ROW ACCESS POLICY SENSITIVE_DX_RAP ON (IS_SENSITIVE);

-- Mortality: owner and doctors only.
CREATE ROW ACCESS POLICY IF NOT EXISTS MORTALITY_RAP AS (pid STRING) RETURNS BOOLEAN ->
  IS_ROLE_IN_SESSION('MV_APP_OWNER') OR IS_ROLE_IN_SESSION('MV_DOCTOR');
ALTER TABLE DEATH_RECORDS ADD ROW ACCESS POLICY MORTALITY_RAP ON (PATIENT_ID);

-- Aggregated, k-suppressed views for management.
CREATE OR REPLACE SECURE VIEW V_DEPT_WORKLOAD AS
  SELECT d.DEPARTMENT_NAME, DATE_TRUNC('month', e.ADMIT_DATE) MONTH, COUNT(*) ENCOUNTERS, COUNT(DISTINCT e.PATIENT_ID) PATIENTS
  FROM ENCOUNTERS e JOIN DEPARTMENTS d USING (DEPARTMENT_ID) GROUP BY ALL HAVING COUNT(DISTINCT e.PATIENT_ID) >= 10;
CREATE OR REPLACE SECURE VIEW V_BUDGET_UTILISATION AS
  SELECT d.DEPARTMENT_NAME, b.FISCAL_YEAR, b.BUDGET_AMOUNT,
         (SELECT COALESCE(SUM(x.AMOUNT), 0) FROM EXPENSES x WHERE x.DEPARTMENT_ID = b.DEPARTMENT_ID AND YEAR(x.EXPENSE_DATE) = b.FISCAL_YEAR) EXPENSES
  FROM DEPT_BUDGETS b JOIN DEPARTMENTS d USING (DEPARTMENT_ID);

