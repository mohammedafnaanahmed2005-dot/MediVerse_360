-- Phase 11: user designation + typing time limit, Laboratory Docs storage.
-- Run as MV_APP_OWNER.
USE ROLE MV_APP_OWNER;

ALTER TABLE MEDIVERSE360.SECURITY.APP_USERS ADD COLUMN IF NOT EXISTS DESIGNATION VARCHAR(80);
-- Maximum seconds allowed to type the verification phrase at sign-in (NULL = no limit).
ALTER TABLE MEDIVERSE360.SECURITY.APP_USERS ADD COLUMN IF NOT EXISTS TYPING_MAX_SECONDS NUMBER(5,1);

CREATE STAGE IF NOT EXISTS MEDIVERSE360.APP.LAB_DOCS_STAGE
  ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE') DIRECTORY = (ENABLE = TRUE)
  COMMENT = 'Laboratory report uploads (LAB_STAFF only, via the app)';

CREATE TABLE IF NOT EXISTS MEDIVERSE360.APP.LAB_DOCUMENTS (
  DOC_ID        VARCHAR(20) PRIMARY KEY,
  PATIENT_ID    VARCHAR(20) NOT NULL,
  LAB_ORDER_ID  VARCHAR(20),
  DOC_TYPE      VARCHAR(40) NOT NULL,
  FILE_NAME     VARCHAR(200) NOT NULL,
  STAGE_PATH    VARCHAR(400) NOT NULL,
  SIZE_BYTES    NUMBER,
  NOTES         VARCHAR(1000),
  UPLOADED_BY   VARCHAR(40) NOT NULL,
  UPLOADED_AT   TIMESTAMP_NTZ DEFAULT SYSDATE()
);
